# Declaración de variables
nombre = "Firulais"
edad = 3
print(nombre)
print(edad)
raza: str = "Labrador"
print(raza)

print("Tipos de Variables")
print("Tipo Texto o String")
gato_refugio = "Mishi"
print(gato_refugio)
print(type(gato_refugio))
print("Tipo de Variable Entera")
jaula = 7
print(jaula)
print(type(jaula))
print("Tipo de Variable Flotante float .decimal")
costo_adopcion = 45.5
print(costo_adopcion)
print(type(costo_adopcion))
print("Tipo de Variable Booleana bool (True o False)")
refugio_abierto = True
print(refugio_abierto)
print(type(refugio_abierto))

mascotas_disponibles = 5
print("mascotas_disponibles")
print(mascotas_disponibles)
mascotas_disponibles = 5 + 5
print(mascotas_disponibles)
mascotas_disponibles += 5
print(mascotas_disponibles)
